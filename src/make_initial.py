background=-0.25
biases=[-10.0,-7.0,-9.0,-9.5,-9.0,-9.5,-8.7,-8.0,-10.0,-9.0]
weights=[]
for digit in map(str,range(10)):
 rows=GLYPHS[digit].strip().splitlines()
 assert len(rows)==14 and all(len(row)==14 for row in rows),digit
 weights.append([ink if x=='#' else background for row in rows for x in row])
params={'experiment':'exp-001-handwritten-baseline','input_shape':[14,14],
 'architecture':'flatten(2x2 meanpool) -> 10 linear logits -> argmax',
 'weight_shape':[10,196],'weights':weights,'biases':biases,
 'authoring':'All weight values and biases explicitly specified in make_initial.py; no fitting, gradient descent or parameter estimation.'}
base=Path(__file__).resolve().parent.parent
out=base/'experiments/exp-001-handwritten-baseline/parameters.json'
out.write_text(json.dumps(params,ensure_ascii=False,indent=2)+'\n')
